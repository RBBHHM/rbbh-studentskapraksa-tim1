namespace RBI.DesignSystem.Components.Typography;

/// <summary>Responsive display type sizes.</summary>
public enum RbiDisplaySize
{
    /// <summary>24, 30 and 36 pixels across source breakpoints.</summary>
    Medium,
    /// <summary>30, 36 and 48 pixels across source breakpoints.</summary>
    Large,
    /// <summary>36, 48 and 60 pixels across source breakpoints.</summary>
    XLarge,
}

/// <summary>Semantic display elements, independent from type size.</summary>
public enum RbiDisplayElement
{
    /// <summary>Level-one heading.</summary>
    Heading1,
    /// <summary>Level-two heading.</summary>
    Heading2,
    /// <summary>Level-three heading.</summary>
    Heading3,
    /// <summary>Paragraph.</summary>
    Paragraph,
    /// <summary>Inline span.</summary>
    Span,
    /// <summary>Generic block.</summary>
    Div,
}
